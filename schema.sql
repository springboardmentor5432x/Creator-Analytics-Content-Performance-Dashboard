-- PostgreSQL schema for: Content Intelligence Platform for Social Media
-- Performance and Creator Growth Analytics
-- Based on the mentor-provided ER diagram, with explicit constraints/indexes.

CREATE TABLE users (
    user_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(50) NOT NULL DEFAULT 'creator'
                  CHECK (role IN ('creator', 'agency', 'admin')),
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE creators (
    creator_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT NOT NULL UNIQUE REFERENCES users(user_id) ON DELETE CASCADE,
    creator_name  VARCHAR(100) NOT NULL,
    bio           TEXT,
    profile_image VARCHAR(255),
    website       VARCHAR(255),
    location      VARCHAR(100),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE social_accounts (
    account_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    creator_id       BIGINT NOT NULL REFERENCES creators(creator_id) ON DELETE CASCADE,
    platform         VARCHAR(50) NOT NULL,
    username         VARCHAR(100) NOT NULL,
    platform_user_id VARCHAR(255),
    followers        INTEGER NOT NULL DEFAULT 0 CHECK (followers >= 0),
    access_token     TEXT, -- encrypt at rest; never expose to the frontend
    refresh_token    TEXT, -- encrypt at rest; never expose to the frontend
    token_expires_at TIMESTAMPTZ,
    is_active        BOOLEAN NOT NULL DEFAULT TRUE,
    connected_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (platform, platform_user_id)
);

CREATE TABLE posts (
    post_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id      BIGINT NOT NULL REFERENCES social_accounts(account_id) ON DELETE CASCADE,
    platform_post_id VARCHAR(255),
    content_type    VARCHAR(50) NOT NULL CHECK (content_type IN ('video', 'image', 'reel', 'text', 'carousel', 'short')),
    caption         TEXT,
    hashtags        TEXT,
    thumbnail_url   VARCHAR(255),
    post_url        TEXT,
    published_at    TIMESTAMPTZ,
    fetched_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (account_id, platform_post_id)
);

CREATE TABLE post_analytics (
    analytics_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id       BIGINT NOT NULL UNIQUE REFERENCES posts(post_id) ON DELETE CASCADE,
    views         BIGINT NOT NULL DEFAULT 0 CHECK (views >= 0),
    likes         BIGINT NOT NULL DEFAULT 0 CHECK (likes >= 0),
    comments      BIGINT NOT NULL DEFAULT 0 CHECK (comments >= 0),
    shares        BIGINT NOT NULL DEFAULT 0 CHECK (shares >= 0),
    saves         BIGINT NOT NULL DEFAULT 0 CHECK (saves >= 0),
    reach         BIGINT NOT NULL DEFAULT 0 CHECK (reach >= 0),
    impressions   BIGINT NOT NULL DEFAULT 0 CHECK (impressions >= 0),
    watch_time    DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (watch_time >= 0),
    engagement_rate DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (engagement_rate >= 0),
    recorded_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE audience_analytics (
    audience_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id       BIGINT NOT NULL REFERENCES social_accounts(account_id) ON DELETE CASCADE,
    date             DATE NOT NULL,
    followers        INTEGER NOT NULL DEFAULT 0 CHECK (followers >= 0),
    following        INTEGER NOT NULL DEFAULT 0 CHECK (following >= 0),
    impressions      BIGINT NOT NULL DEFAULT 0 CHECK (impressions >= 0),
    reach            BIGINT NOT NULL DEFAULT 0 CHECK (reach >= 0),
    profile_visits   INTEGER NOT NULL DEFAULT 0 CHECK (profile_visits >= 0),
    male_percentage  REAL CHECK (male_percentage BETWEEN 0 AND 100),
    female_percentage REAL CHECK (female_percentage BETWEEN 0 AND 100),
    top_location     VARCHAR(100),
    active_hours     JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (account_id, date)
);

CREATE TABLE revenue (
    revenue_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    creator_id  BIGINT NOT NULL REFERENCES creators(creator_id) ON DELETE CASCADE,
    title       VARCHAR(255) NOT NULL,
    source      VARCHAR(50) NOT NULL CHECK (source IN ('sponsorship', 'ad_revenue', 'affiliate', 'brand_deal', 'subscription', 'other')),
    amount      NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
    currency    VARCHAR(10) NOT NULL DEFAULT 'INR',
    date        DATE NOT NULL,
    description TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE reports (
    report_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    creator_id  BIGINT NOT NULL REFERENCES creators(creator_id) ON DELETE CASCADE,
    report_type VARCHAR(50) NOT NULL CHECK (report_type IN ('monthly', 'audience', 'content', 'revenue', 'comparison', 'custom')),
    file_path   VARCHAR(255),
    file_format VARCHAR(10) CHECK (file_format IN ('pdf', 'excel', 'csv')),
    generated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE notifications (
    notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    message         TEXT NOT NULL,
    type            VARCHAR(50) NOT NULL CHECK (type IN ('info', 'success', 'warning', 'error')),
    is_read         BOOLEAN NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE saved_reports (
    saved_report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    name            VARCHAR(100) NOT NULL,
    filters         JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE platform_stats (
    stat_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id       BIGINT NOT NULL REFERENCES social_accounts(account_id) ON DELETE CASCADE,
    date             DATE NOT NULL,
    total_posts      INTEGER NOT NULL DEFAULT 0 CHECK (total_posts >= 0),
    total_views      BIGINT NOT NULL DEFAULT 0 CHECK (total_views >= 0),
    total_likes      BIGINT NOT NULL DEFAULT 0 CHECK (total_likes >= 0),
    total_comments   BIGINT NOT NULL DEFAULT 0 CHECK (total_comments >= 0),
    total_shares     BIGINT NOT NULL DEFAULT 0 CHECK (total_shares >= 0),
    follower_gain    INTEGER NOT NULL DEFAULT 0,
    engagement_rate DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (engagement_rate >= 0),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (account_id, date)
);

-- Common lookup/reporting indexes
CREATE INDEX idx_creators_user_id ON creators(user_id);
CREATE INDEX idx_social_accounts_creator ON social_accounts(creator_id);
CREATE INDEX idx_posts_account_published ON posts(account_id, published_at DESC);
CREATE INDEX idx_post_analytics_recorded ON post_analytics(recorded_at DESC);
CREATE INDEX idx_audience_account_date ON audience_analytics(account_id, date DESC);
CREATE INDEX idx_revenue_creator_date ON revenue(creator_id, date DESC);
CREATE INDEX idx_notifications_user_unread ON notifications(user_id, is_read, created_at DESC);
CREATE INDEX idx_platform_stats_account_date ON platform_stats(account_id, date DESC);
